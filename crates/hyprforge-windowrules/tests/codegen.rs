use hyprforge_windowrules::model::{Effects, Matcher, Opacity, Rule};
use hyprforge_windowrules::{codegen::generate, storage};

fn discord_rule() -> Rule {
    Rule {
        name: "hyprforge-discord-1".to_string(),
        enabled: true,
        matcher: Matcher {
            class: Some("discord".to_string()),
            ..Default::default()
        },
        effects: Effects {
            float: Some(true),
            ..Default::default()
        },
    }
}

#[test]
fn generates_basic_rule() {
    let lua = generate(&[discord_rule()]);
    assert!(lua.contains("name = [[hyprforge-discord-1]]"));
    assert!(lua.contains("match = { class = [[discord]] }"));
    assert!(lua.contains("float = true"));
    assert!(lua.starts_with("-- Generated by Hyprforge"));
}

#[test]
fn skips_empty_matcher() {
    let rule = Rule {
        name: "hyprforge-empty-1".to_string(),
        enabled: true,
        matcher: Matcher::default(),
        effects: Effects::default(),
    };
    let lua = generate(&[rule]);
    assert!(!lua.contains("hyprforge-empty-1"));
}

#[test]
fn preserves_order() {
    let mut a = discord_rule();
    a.name = "hyprforge-a-1".to_string();
    let mut b = discord_rule();
    b.name = "hyprforge-b-1".to_string();

    let lua = generate(&[a, b]);
    let pos_a = lua.find("hyprforge-a-1").unwrap();
    let pos_b = lua.find("hyprforge-b-1").unwrap();
    assert!(pos_a < pos_b);
}

#[test]
fn opacity_override_serializes_with_suffix() {
    let rule = Rule {
        name: "hyprforge-kitty-1".to_string(),
        enabled: true,
        matcher: Matcher {
            class: Some("kitty".to_string()),
            ..Default::default()
        },
        effects: Effects {
            opacity: Opacity {
                active: Some(0.8),
                inactive: Some(0.8),
                fullscreen: Some(1.0),
                is_override: true,
            },
            ..Default::default()
        },
    };
    let lua = generate(&[rule]);
    assert!(lua.contains("opacity = [[0.8 override 0.8 override 1 override]]"));
}

#[test]
fn regex_strings_pass_through_verbatim() {
    let rule = Rule {
        name: "hyprforge-regexy-1".to_string(),
        enabled: true,
        matcher: Matcher {
            title: Some(r"^(foo|bar)\.exe$".to_string()),
            ..Default::default()
        },
        effects: Effects::default(),
    };
    let lua = generate(&[rule]);
    assert!(lua.contains(r"title = [[^(foo|bar)\.exe$]]"));
}

#[test]
fn move_expression_vs_literal() {
    let rule = Rule {
        name: "hyprforge-move-1".to_string(),
        enabled: true,
        matcher: Matcher {
            class: Some("x".to_string()),
            ..Default::default()
        },
        effects: Effects {
            r#move: Some([
                "100".to_string(),
                "cursor_y-(window_h*0.5)".to_string(),
            ]),
            ..Default::default()
        },
    };
    let lua = generate(&[rule]);
    assert!(lua.contains("move = { 100, [[cursor_y-(window_h*0.5)]] }"));
}

#[test]
fn toml_round_trip_preserves_order_and_fields() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("window-rules.toml");

    let rules = vec![discord_rule(), {
        let mut r = discord_rule();
        r.name = "hyprforge-slack-1".to_string();
        r.matcher.class = Some("slack".to_string());
        r.effects.rounding = Some(8);
        r
    }];

    storage::save(&path, &rules).unwrap();
    let loaded = storage::load(&path).unwrap();
    assert_eq!(loaded, rules);
}

#[test]
fn load_missing_file_is_empty_not_error() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("nope.toml");
    let rules = storage::load(&path).unwrap();
    assert!(rules.is_empty());
}
