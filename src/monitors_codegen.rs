//! Renders the live, settled layout as static `hl.monitor()` calls —
//! `monitors.lua`, sourced via `require("hyprforge/monitors")`.
//!
//! This is deliberately not a full re-implementation of the daemon's
//! fingerprint-matching logic: it's a "last known good" snapshot Hyprland
//! can apply on its own startup/reload, so a saved layout survives even
//! when `hyprforge-displayd` isn't running to reassert it over
//! `wlr-output-management-v1`. The daemon still owns the live, adaptive
//! behavior — this file is only ever regenerated wholesale, never hand
//! -edited or read back.

use crate::types::{Head, Transform};
use hyprforge_core::geometry::nearest_valid_scale;
use std::collections::HashMap;

const HEADER: &str = "-- Generated by Hyprforge. Do not edit by hand — changes will be\n-- overwritten the next time the display daemon settles a layout.\n";

/// One output as it should be described to Hyprland. `selector` is
/// Hyprland's own `desc:<description>` string (or a bare connector name as
/// a fallback) — never displayd's own EDID description, which is not
/// guaranteed to match how Hyprland formats the same field.
#[derive(Debug, Clone, PartialEq)]
pub struct MonitorEntry {
    pub selector: String,
    pub enabled: bool,
    /// `None` only when `enabled` is false — a disabled output's mode is
    /// irrelevant.
    pub mode: Option<(i32, i32, i32)>,
    pub position: (i32, i32),
    /// Already snapped to an achievable `k/120` scale — the caller's job,
    /// same division of concerns `HeadRecord::from_head` uses in
    /// `profile.rs`. Emitting the raw wire value here would write an odd
    /// off-preset number into a file meant to be a stable fallback.
    pub scale: f64,
    pub transform: Transform,
}

/// Builds the entries to render from the live, settled heads plus
/// Hyprland's own connector→description map (see
/// [`crate::hyprctl_monitors::connector_descriptions`] for why that map
/// can't come from `Head` itself).
///
/// A connector missing from `descriptions` — `hyprctl` unreachable, or that
/// output simply has no description to report — falls back to the bare
/// connector name, same rule `Monitor::rule_selector` uses in
/// `hyprforge-windowrules`. That's a weaker selector (doesn't survive a
/// replug), but still strictly better than omitting the output from the
/// fallback file entirely.
pub fn entries_from_heads(heads: &[Head], descriptions: &HashMap<String, String>) -> Vec<MonitorEntry> {
    heads
        .iter()
        .map(|head| {
            let selector = match descriptions.get(&head.connector) {
                Some(desc) if !desc.trim().is_empty() => format!("desc:{}", desc.trim()),
                _ => head.connector.clone(),
            };
            let mode = head.effective_mode().map(|m| (m.width, m.height, m.refresh_mhz));
            let (width, height) = mode.map(|(w, h, _)| (w, h)).unwrap_or((0, 0));
            MonitorEntry {
                selector,
                enabled: head.enabled,
                mode: head.enabled.then_some(mode).flatten(),
                position: head.position,
                scale: nearest_valid_scale(width, height, head.scale),
                transform: head.transform,
            }
        })
        .collect()
}

/// Renders `entries` to a complete `monitors.lua` body.
pub fn generate(entries: &[MonitorEntry]) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    for entry in entries {
        out.push_str(&render(entry));
    }
    out
}

fn render(entry: &MonitorEntry) -> String {
    if !entry.enabled {
        return format!(
            "hl.monitor({{ output = {}, disabled = true }})\n",
            lua_string(&entry.selector),
        );
    }
    let mode = match entry.mode {
        Some((width, height, refresh_mhz)) => {
            format!("{width}x{height}@{:.2}", refresh_mhz as f64 / 1000.0)
        }
        None => "preferred".to_string(),
    };
    let (x, y) = entry.position;
    format!(
        "hl.monitor({{ output = {}, mode = {}, position = {}, scale = {}, transform = {} }})\n",
        lua_string(&entry.selector),
        lua_string(&mode),
        lua_string(&format!("{x}x{y}")),
        entry.scale,
        transform_index(entry.transform),
    )
}

/// Hyprland's `transform` field is the `wl_output.transform` enum's own
/// integer values (0–7) — the same numbering `backend/wlr.rs` converts
/// to/from at the protocol boundary, spelled out explicitly here too rather
/// than relied on as an implicit enum discriminant.
fn transform_index(t: Transform) -> u8 {
    match t {
        Transform::Normal => 0,
        Transform::Rotate90 => 1,
        Transform::Rotate180 => 2,
        Transform::Rotate270 => 3,
        Transform::Flipped => 4,
        Transform::Flipped90 => 5,
        Transform::Flipped180 => 6,
        Transform::Flipped270 => 7,
    }
}

/// Quotes with a Lua long bracket, which needs no escaping, so a `desc:`
/// string containing regex-like or quote characters can never break the
/// generated call's own parse.
///
/// The one implementation all three generating crates share — this crate's
/// former copy got the fallback condition wrong in the same way the other
/// two did. See [`hyprforge_core::lua`].
use hyprforge_core::lua::lua_string;

#[cfg(test)]
mod tests {
    use super::*;

    fn enabled_entry() -> MonitorEntry {
        MonitorEntry {
            selector: "desc:BOE 0x0BC9".to_string(),
            enabled: true,
            mode: Some((2560, 1600, 60000)),
            position: (0, 0),
            scale: 1.25,
            transform: Transform::Normal,
        }
    }

    fn head(connector: &str, enabled: bool) -> Head {
        let mode = crate::types::Mode { width: 2560, height: 1600, refresh_mhz: 60000, preferred: true };
        Head {
            connector: connector.to_string(),
            identity: crate::types::Identity::default(),
            description: "displayd's own EDID description (must not be used)".to_string(),
            modes: vec![mode],
            current_mode: Some(mode),
            position: (0, 0),
            transform: Transform::Normal,
            scale: 1.25,
            enabled,
        }
    }

    #[test]
    fn a_known_connector_gets_a_desc_selector_from_hyprctls_own_map() {
        let heads = vec![head("eDP-1", true)];
        let descriptions = HashMap::from([("eDP-1".to_string(), "BOE 0x0BC9".to_string())]);
        let entries = entries_from_heads(&heads, &descriptions);
        assert_eq!(entries[0].selector, "desc:BOE 0x0BC9");
    }

    /// Displayd's own `Head.description` must never leak into the
    /// selector — see the module docs for why the two aren't
    /// interchangeable.
    #[test]
    fn an_unknown_connector_falls_back_to_the_bare_connector_not_displayds_description() {
        let heads = vec![head("eDP-1", true)];
        let entries = entries_from_heads(&heads, &HashMap::new());
        assert_eq!(entries[0].selector, "eDP-1");
    }

    #[test]
    fn a_disabled_head_carries_no_mode() {
        let heads = vec![head("eDP-1", false)];
        let entries = entries_from_heads(&heads, &HashMap::new());
        assert!(!entries[0].enabled);
        assert_eq!(entries[0].mode, None);
    }

    #[test]
    fn scale_is_snapped_to_an_achievable_120th_not_the_raw_wire_value() {
        let mut heads = vec![head("eDP-1", true)];
        // Not a valid k/120 for 2560x1600 — nearest_valid_scale must correct
        // it rather than passing it straight through.
        heads[0].scale = 1.5;
        let entries = entries_from_heads(&heads, &HashMap::new());
        assert_ne!(entries[0].scale, 1.5);
    }

    #[test]
    fn empty_input_is_just_the_header() {
        let lua = generate(&[]);
        assert!(lua.starts_with("-- Generated by Hyprforge"));
        assert!(!lua.contains("hl.monitor"));
    }

    #[test]
    fn renders_an_enabled_output() {
        let lua = generate(&[enabled_entry()]);
        assert!(
            lua.contains(
                "hl.monitor({ output = [[desc:BOE 0x0BC9]], mode = [[2560x1600@60.00]], \
                 position = [[0x0]], scale = 1.25, transform = 0 })"
            ),
            "got: {lua}"
        );
    }

    #[test]
    fn a_disabled_entry_omits_mode_position_and_scale() {
        let mut entry = enabled_entry();
        entry.enabled = false;
        let lua = generate(&[entry]);
        assert!(lua.contains("hl.monitor({ output = [[desc:BOE 0x0BC9]], disabled = true })"));
        assert!(!lua.contains("mode"));
        assert!(!lua.contains("scale"));
    }

    #[test]
    fn a_missing_mode_falls_back_to_preferred() {
        let mut entry = enabled_entry();
        entry.mode = None;
        let lua = generate(&[entry]);
        assert!(lua.contains("mode = [[preferred]]"), "got: {lua}");
    }

    #[test]
    fn every_transform_maps_to_hyprlands_own_numbering() {
        let cases = [
            (Transform::Normal, 0),
            (Transform::Rotate90, 1),
            (Transform::Rotate180, 2),
            (Transform::Rotate270, 3),
            (Transform::Flipped, 4),
            (Transform::Flipped90, 5),
            (Transform::Flipped180, 6),
            (Transform::Flipped270, 7),
        ];
        for (transform, expected) in cases {
            let mut entry = enabled_entry();
            entry.transform = transform;
            let lua = generate(&[entry]);
            assert!(
                lua.contains(&format!("transform = {expected} }}")),
                "transform {transform:?} should map to {expected}, got: {lua}"
            );
        }
    }

    #[test]
    fn a_fractional_refresh_rate_keeps_two_decimals() {
        let mut entry = enabled_entry();
        entry.mode = Some((1920, 1080, 59940));
        let lua = generate(&[entry]);
        assert!(lua.contains("1920x1080@59.94"), "got: {lua}");
    }

    #[test]
    fn a_connector_only_selector_needs_no_desc_prefix() {
        let mut entry = enabled_entry();
        entry.selector = "eDP-1".to_string();
        let lua = generate(&[entry]);
        assert!(lua.contains("output = [[eDP-1]]"), "got: {lua}");
    }

    #[test]
    fn multiple_entries_each_get_their_own_call() {
        let lua = generate(&[enabled_entry(), enabled_entry()]);
        assert_eq!(lua.matches("hl.monitor").count(), 2);
    }
}
